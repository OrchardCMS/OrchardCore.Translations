// Tooling for the translation editor (a file-based app, .NET 10 or later).
//
//   dotnet run editor/site.cs -- serve [--port 5080]
//       Serves the editor against this checkout: editor/wwwroot at /, the catalogs at
//       /Localization and a freshly computed /data/index.json.
//
//   dotnet run editor/site.cs -- build --out _site
//       Writes the static site that GitHub Pages hosts: the editor, a copy of the
//       .pot/.po files and data/index.json.
//
// This program only counts entries for the dashboard. Everything that edits .po files
// lives in wwwroot/js; a test compares both readers so they cannot drift apart.

using System.Diagnostics;
using System.Runtime.CompilerServices;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.AspNetCore.StaticFiles;
using Microsoft.Extensions.FileProviders;

string? Option(string name)
{
    var index = Array.IndexOf(args, name);
    return index >= 0 && index + 1 < args.Length ? args[index + 1] : null;
}

var editorDir = Site.FindEditorDirectory(Option("--root"));
if (editorDir is null)
{
    Console.Error.WriteLine("Cannot find the 'editor/wwwroot' folder. Run from the repository or pass --root <repository>.");
    return 1;
}

var repoRoot = Path.GetFullPath(Path.Combine(editorDir, ".."));
var webRoot = Path.Combine(editorDir, "wwwroot");
var localization = Path.Combine(repoRoot, "Localization");
var command = args.Length > 0 && !args[0].StartsWith('-') ? args[0] : "serve";

switch (command)
{
    case "build":
    {
        var output = Path.GetFullPath(Option("--out") ?? "_site");
        var marker = Path.Combine(output, ".po-editor-site");
        if (Directory.Exists(output) && Directory.EnumerateFileSystemEntries(output).Any())
        {
            if (!File.Exists(marker))
            {
                Console.Error.WriteLine($"'{output}' is not empty and was not created by this tool. Choose another --out folder.");
                return 1;
            }
            Directory.Delete(output, recursive: true);
        }

        Directory.CreateDirectory(output);
        File.WriteAllText(marker, "Generated by editor/site.cs\n");
        File.WriteAllText(Path.Combine(output, ".nojekyll"), "");

        var files = 0;
        foreach (var file in Directory.EnumerateFiles(webRoot, "*", SearchOption.AllDirectories))
        {
            Site.Copy(file, Path.Combine(output, Path.GetRelativePath(webRoot, file)));
            files++;
        }

        foreach (var file in Site.CatalogFiles(localization))
        {
            Site.Copy(file, Path.Combine(output, "Localization", Path.GetRelativePath(localization, file)));
            files++;
        }

        Directory.CreateDirectory(Path.Combine(output, "data"));
        File.WriteAllBytes(Path.Combine(output, "data", "index.json"), Site.BuildIndex(repoRoot));
        Console.WriteLine($"Wrote {files} files and data/index.json to {output}");
        return 0;
    }

    case "serve":
    {
        var port = int.TryParse(Option("--port"), out var parsed) ? parsed : 5080;
        if (!Site.IsPortFree(port))
        {
            Console.Error.WriteLine($"Port {port} is already in use. The editor may already be running at http://localhost:{port}/; otherwise pass --port <number>.");
            return 1;
        }

        var builder = WebApplication.CreateBuilder(new WebApplicationOptions { ContentRootPath = editorDir, WebRootPath = webRoot });
        builder.WebHost.UseUrls($"http://localhost:{port}");
        var app = builder.Build();

        // Always serve the working tree as it is now.
        app.Use((context, next) =>
        {
            context.Response.Headers.CacheControl = "no-cache";
            return next(context);
        });

        app.MapGet("/data/index.json", (HttpContext context) =>
        {
            context.Response.ContentType = "application/json; charset=utf-8";
            return context.Response.Body.WriteAsync(Site.BuildIndex(repoRoot)).AsTask();
        });

        app.UseDefaultFiles();
        app.UseStaticFiles();
        app.UseStaticFiles(new StaticFileOptions
        {
            FileProvider = new PhysicalFileProvider(localization),
            RequestPath = "/Localization",
            ContentTypeProvider = new FileExtensionContentTypeProvider(new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase)
            {
                [".po"] = "text/plain; charset=utf-8",
                [".pot"] = "text/plain; charset=utf-8",
            }),
        });

        Console.WriteLine($"Translation editor: http://localhost:{port}/  (tests: http://localhost:{port}/tests.html)");
        app.Run();
        return 0;
    }

    default:
        Console.Error.WriteLine("Usage: dotnet run editor/site.cs -- serve [--port 5080] | build --out <folder>");
        return 1;
}

static class Site
{
    /// <summary>The folder that contains this file, falling back to a search from the current directory.</summary>
    public static string? FindEditorDirectory(string? root, [CallerFilePath] string sourcePath = "")
    {
        var candidates = new List<string?>
        {
            root is null ? null : Path.Combine(root, "editor"),
            Path.GetDirectoryName(sourcePath),
        };

        for (var dir = new DirectoryInfo(Directory.GetCurrentDirectory()); dir is not null; dir = dir.Parent)
        {
            candidates.Add(Path.Combine(dir.FullName, "editor"));
        }

        return candidates.FirstOrDefault(c => !string.IsNullOrEmpty(c) && Directory.Exists(Path.Combine(c, "wwwroot")) && Directory.Exists(Path.Combine(c, "..", "Localization")));
    }

    public static bool IsPortFree(int port)
    {
        try
        {
            using var listener = new System.Net.Sockets.TcpListener(System.Net.IPAddress.Loopback, port);
            listener.Start();
            listener.Stop();
            return true;
        }
        catch (System.Net.Sockets.SocketException)
        {
            return false;
        }
    }

    public static void Copy(string source, string destination)
    {
        Directory.CreateDirectory(Path.GetDirectoryName(destination)!);
        File.Copy(source, destination, overwrite: true);
    }

    /// <summary>Localization/*.pot and Localization/&lt;culture&gt;/*.po.</summary>
    public static IEnumerable<string> CatalogFiles(string localization)
    {
        foreach (var file in Directory.EnumerateFiles(localization, "*.pot"))
        {
            yield return file;
        }

        foreach (var culture in Directory.EnumerateDirectories(localization))
        {
            foreach (var file in Directory.EnumerateFiles(culture, "*.po"))
            {
                yield return file;
            }
        }
    }

    /// <summary>
    /// The statistics index: for every culture and file, how many template entries are
    /// translated, partially translated (plurals), empty or missing, and how many
    /// entries are deprecated (no longer in the template).
    /// </summary>
    public static byte[] BuildIndex(string repoRoot)
    {
        var localization = Path.Combine(repoRoot, "Localization");

        var templates = Directory.EnumerateFiles(localization, "*.pot")
            .Select(path => (Name: Path.GetFileNameWithoutExtension(path), Catalog: Catalog.Read(path)))
            .OrderBy(t => t.Name, StringComparer.Ordinal)
            .ToList();
        var templatesByName = templates.ToDictionary(t => t.Name, t => t.Catalog, StringComparer.Ordinal);

        var cultureFolders = Directory.EnumerateDirectories(localization)
            .Where(path => !Path.GetFileName(path).StartsWith('.'))
            .OrderBy(path => Path.GetFileName(path), StringComparer.Ordinal)
            .ToList();
        var cultureFiles = new SortedDictionary<string, int[]>[cultureFolders.Count];

        Parallel.For(0, cultureFolders.Count, i =>
        {
            var result = new SortedDictionary<string, int[]>(StringComparer.Ordinal);
            foreach (var path in Directory.EnumerateFiles(cultureFolders[i], "*.po"))
            {
                var name = Path.GetFileNameWithoutExtension(path);
                result[name] = Catalog.Compare(templatesByName.GetValueOrDefault(name), Catalog.Read(path));
            }

            cultureFiles[i] = result;
        });

        var names = CultureNames(repoRoot);
        using var stream = new MemoryStream();
        using (var json = new Utf8JsonWriter(stream))
        {
            json.WriteStartObject();
            json.WriteString("commit", CurrentCommit(repoRoot));
            json.WriteString("generated", DateTime.UtcNow.ToString("yyyy-MM-ddTHH:mm:ssZ"));

            json.WriteStartArray("templates");
            foreach (var (name, catalog) in templates)
            {
                json.WriteStartObject();
                json.WriteString("name", name);
                json.WriteNumber("entries", catalog.Entries.Count);
                json.WriteEndObject();
            }

            json.WriteEndArray();

            json.WriteStartArray("cultures");
            for (var i = 0; i < cultureFolders.Count; i++)
            {
                var code = Path.GetFileName(cultureFolders[i]);
                json.WriteStartObject();
                json.WriteString("code", code);
                json.WriteString("name", names.GetValueOrDefault(code, ""));
                json.WriteStartObject("files");
                foreach (var (name, stats) in cultureFiles[i])
                {
                    json.WriteStartArray(name);
                    foreach (var value in stats)
                    {
                        json.WriteNumberValue(value);
                    }

                    json.WriteEndArray();
                }

                json.WriteEndObject();
                json.WriteEndObject();
            }

            json.WriteEndArray();
            json.WriteEndObject();
        }

        return stream.ToArray();
    }

    private static Dictionary<string, string> CultureNames(string repoRoot)
    {
        var names = new Dictionary<string, string>(StringComparer.Ordinal);
        var path = Path.Combine(repoRoot, "cultures.json");
        if (!File.Exists(path))
        {
            return names;
        }

        using var document = JsonDocument.Parse(File.ReadAllText(path));
        foreach (var culture in document.RootElement.GetProperty("cultures").EnumerateArray())
        {
            if (culture.TryGetProperty("folder", out var folder) && culture.TryGetProperty("display-name", out var display))
            {
                names[folder.GetString()!] = display.GetString() ?? "";
            }
        }

        return names;
    }

    private static string CurrentCommit(string repoRoot)
    {
        var fromEnvironment = Environment.GetEnvironmentVariable("GITHUB_SHA");
        if (!string.IsNullOrWhiteSpace(fromEnvironment))
        {
            return fromEnvironment.Trim();
        }

        try
        {
            var info = new ProcessStartInfo("git", "rev-parse HEAD")
            {
                WorkingDirectory = repoRoot,
                RedirectStandardOutput = true,
                RedirectStandardError = true,
            };
            using var process = Process.Start(info)!;
            var output = process.StandardOutput.ReadToEnd().Trim();
            process.WaitForExit();
            return process.ExitCode == 0 ? output : "";
        }
        catch
        {
            return "";
        }
    }
}

/// <summary>A PO file reduced to what the statistics need.</summary>
sealed partial class Catalog
{
    public sealed record Entry(string Key, bool Plural, List<string> Translations);

    public List<Entry> Entries { get; } = [];

    public int PluralCount { get; private set; } = 2;

    [GeneratedRegex(@"nplurals\s*=\s*(\d+)")]
    private static partial Regex PluralCountPattern();

    /// <summary>[translated, partial, empty, missing, deprecated]</summary>
    public static int[] Compare(Catalog? template, Catalog translation)
    {
        var stats = new int[5];
        var translated = new Dictionary<string, Entry>(StringComparer.Ordinal);
        foreach (var entry in translation.Entries)
        {
            translated.TryAdd(entry.Key, entry);
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        if (template is not null)
        {
            foreach (var source in template.Entries)
            {
                if (!seen.Add(source.Key))
                {
                    continue;
                }

                if (!translated.TryGetValue(source.Key, out var entry))
                {
                    stats[3]++;
                    continue;
                }

                var forms = source.Plural ? translation.PluralCount : 1;
                var filled = 0;
                for (var i = 0; i < forms; i++)
                {
                    if (i < entry.Translations.Count && entry.Translations[i].Length > 0)
                    {
                        filled++;
                    }
                }

                stats[filled == forms ? 0 : filled == 0 ? 2 : 1]++;
            }
        }

        foreach (var key in translated.Keys)
        {
            if (!seen.Contains(key))
            {
                stats[4]++;
            }
        }

        return stats;
    }

    public static Catalog Read(string path)
    {
        var catalog = new Catalog();
        var headerSeen = false;
        var maxPluralForms = 0;
        int? declaredForms = null;

        string? context = null, id = null;
        var plural = false;
        var valid = true;
        var translations = new List<StringBuilder?>();
        StringBuilder? current = null;
        var contextBuilder = new StringBuilder();
        var idBuilder = new StringBuilder();
        var hasContext = false;
        var hasId = false;

        void Flush()
        {
            context = hasContext ? contextBuilder.ToString() : null;
            id = hasId ? idBuilder.ToString() : null;
            if (valid && id is not null && translations.Count > 0 && translations.All(t => t is not null))
            {
                var values = translations.Select(t => t!.ToString()).ToList();
                if (id.Length == 0 && context is null && !headerSeen)
                {
                    headerSeen = true;
                    var header = values[0];
                    var start = header.IndexOf("Plural-Forms:", StringComparison.Ordinal);
                    if (start >= 0)
                    {
                        var end = header.IndexOf("\\n", start, StringComparison.Ordinal);
                        var match = PluralCountPattern().Match(end < 0 ? header[start..] : header[start..end]);
                        if (match.Success && int.TryParse(match.Groups[1].Value, out var n) && n >= 1)
                        {
                            declaredForms = n;
                        }
                    }
                }
                else
                {
                    catalog.Entries.Add(new Entry((context ?? "") + "\u0004" + id, plural, values));
                    if (plural)
                    {
                        maxPluralForms = Math.Max(maxPluralForms, values.Count);
                    }
                }
            }

            contextBuilder.Clear();
            idBuilder.Clear();
            hasContext = hasId = plural = false;
            valid = true;
            translations = [];
            current = null;
        }

        var started = false;
        foreach (var rawLine in File.ReadLines(path, Encoding.UTF8))
        {
            var line = rawLine.Trim();
            if (line.Length == 0)
            {
                if (started)
                {
                    Flush();
                    started = false;
                }

                continue;
            }

            started = true;
            if (line[0] == '#')
            {
                current = null;
                continue;
            }

            var open = line.IndexOf('"');
            var close = line.LastIndexOf('"');
            if (open < 0 || close <= open)
            {
                valid = false;
                continue;
            }

            var value = line.AsSpan(open + 1, close - open - 1);
            var keyword = line.AsSpan(0, open).TrimEnd();
            if (keyword.Length == 0)
            {
                if (current is null)
                {
                    valid = false;
                }
                else
                {
                    current.Append(value);
                }
            }
            else if (keyword is "msgctxt")
            {
                hasContext = true;
                current = contextBuilder.Clear().Append(value);
            }
            else if (keyword is "msgid")
            {
                hasId = true;
                current = idBuilder.Clear().Append(value);
            }
            else if (keyword is "msgid_plural")
            {
                plural = true;
                current = new StringBuilder().Append(value);
            }
            else if (keyword is "msgstr")
            {
                current = SetTranslation(translations, 0, value);
            }
            else if (keyword.StartsWith("msgstr[", StringComparison.Ordinal) && keyword[^1] == ']' && int.TryParse(keyword[7..^1], out var slot) && slot is >= 0 and < 100)
            {
                current = SetTranslation(translations, slot, value);
            }
            else
            {
                valid = false;
            }
        }

        if (started)
        {
            Flush();
        }

        catalog.PluralCount = declaredForms ?? (maxPluralForms > 0 ? maxPluralForms : 2);
        return catalog;
    }

    private static StringBuilder SetTranslation(List<StringBuilder?> translations, int slot, ReadOnlySpan<char> value)
    {
        while (translations.Count <= slot)
        {
            translations.Add(null);
        }

        var builder = new StringBuilder().Append(value);
        translations[slot] = builder;
        return builder;
    }
}
